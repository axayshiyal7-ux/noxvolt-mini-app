-- NoxVolt fresh-start schema. WARNING: this intentionally deletes the listed tables and all their data.
DROP TABLE IF EXISTS task_completions CASCADE;
DROP TABLE IF EXISTS ads CASCADE;
DROP TABLE IF EXISTS withdrawals CASCADE;
DROP TABLE IF EXISTS referrals CASCADE;
DROP TABLE IF EXISTS tasks CASCADE;
DROP TABLE IF EXISTS security_logs CASCADE;
DROP TABLE IF EXISTS users CASCADE;

CREATE TABLE users (
  telegram_id bigint PRIMARY KEY,
  username text,
  first_name text,
  photo_url text,
  referred_by bigint REFERENCES users(telegram_id) ON DELETE SET NULL,
  is_admin boolean NOT NULL DEFAULT false,
  withdrawable_balance numeric(20,2) NOT NULL DEFAULT 0 CHECK (withdrawable_balance >= 0),
  mining_pending numeric(20,2) NOT NULL DEFAULT 0,
  total_earned numeric(20,2) NOT NULL DEFAULT 0,
  ads_watched_total integer NOT NULL DEFAULT 0,
  ads_watched_today integer NOT NULL DEFAULT 0,
  ads_today_reward numeric(20,2) NOT NULL DEFAULT 0,
  ads_today_date date NOT NULL DEFAULT current_date,
  mining_started_at timestamptz,
  mining_last_collect timestamptz,
  wallet text,
  referral_count integer NOT NULL DEFAULT 0,
  referral_earned numeric(20,2) NOT NULL DEFAULT 0,
  flagged boolean NOT NULL DEFAULT false,
  flag_reason text,
  last_active timestamptz NOT NULL DEFAULT now(),
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE TABLE tasks (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  title text NOT NULL,
  channel_url text NOT NULL,
  reward numeric(20,2) NOT NULL DEFAULT 10 CHECK (reward > 0),
  active boolean NOT NULL DEFAULT true,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE task_completions (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telegram_id bigint NOT NULL REFERENCES users(telegram_id) ON DELETE CASCADE,
  task_id bigint NOT NULL REFERENCES tasks(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  UNIQUE (telegram_id, task_id)
);
CREATE TABLE ads (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telegram_id bigint NOT NULL REFERENCES users(telegram_id) ON DELETE CASCADE,
  reward numeric(20,2) NOT NULL CHECK (reward > 0),
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE TABLE withdrawals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telegram_id bigint NOT NULL REFERENCES users(telegram_id) ON DELETE CASCADE,
  username text,
  amount numeric(20,2) NOT NULL CHECK (amount > 0),
  address text NOT NULL,
  status text NOT NULL DEFAULT 'pending' CHECK (status IN ('pending','paid','rejected')),
  created_at timestamptz NOT NULL DEFAULT now(),
  processed_at timestamptz
);
CREATE TABLE referrals (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  referrer_id bigint NOT NULL REFERENCES users(telegram_id) ON DELETE CASCADE,
  referred_id bigint NOT NULL UNIQUE REFERENCES users(telegram_id) ON DELETE CASCADE,
  qualified boolean NOT NULL DEFAULT false,
  created_at timestamptz NOT NULL DEFAULT now(),
  CHECK (referrer_id <> referred_id)
);
CREATE TABLE security_logs (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  telegram_id bigint,
  event_type text NOT NULL,
  details text,
  created_at timestamptz NOT NULL DEFAULT now()
);
CREATE INDEX ads_user_created_idx ON ads (telegram_id, created_at DESC);
CREATE INDEX withdrawals_status_created_idx ON withdrawals (status, created_at DESC);
CREATE INDEX users_last_active_idx ON users (last_active DESC);

