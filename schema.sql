-- NoxVolt transactional operations. Install after the table definitions in schema.sql.
CREATE OR REPLACE FUNCTION noxvolt_grant_ad_reward(
  p_telegram_id bigint, p_reward numeric, p_referral_reward numeric, p_referral_ads_required integer
) RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE u users%ROWTYPE; ref referrals%ROWTYPE; bonus_paid boolean := false; utc_today date := (now() AT TIME ZONE 'UTC')::date;
BEGIN
  SELECT * INTO u FROM users WHERE telegram_id = p_telegram_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'User account not found'; END IF;
  IF EXISTS (SELECT 1 FROM ads WHERE telegram_id = p_telegram_id AND created_at > now() - interval '30 seconds') THEN
    RAISE EXCEPTION 'Please wait 30 seconds before the next reward';
  END IF;
  INSERT INTO ads (telegram_id, reward) VALUES (p_telegram_id, p_reward);
  UPDATE users SET
    withdrawable_balance = withdrawable_balance + p_reward,
    total_earned = total_earned + p_reward,
    ads_watched_total = ads_watched_total + 1,
    ads_watched_today = CASE WHEN ads_today_date = utc_today THEN ads_watched_today + 1 ELSE 1 END,
    ads_today_reward = CASE WHEN ads_today_date = utc_today THEN ads_today_reward + p_reward ELSE p_reward END,
    ads_today_date = utc_today
  WHERE telegram_id = p_telegram_id RETURNING * INTO u;
  IF u.referred_by IS NOT NULL AND u.ads_watched_total >= p_referral_ads_required THEN
    SELECT * INTO ref FROM referrals WHERE referred_id = p_telegram_id AND NOT qualified FOR UPDATE;
    IF FOUND THEN
      UPDATE referrals SET qualified = true WHERE id = ref.id;
      UPDATE users SET withdrawable_balance = withdrawable_balance + p_referral_reward,
        total_earned = total_earned + p_referral_reward, referral_count = referral_count + 1,
        referral_earned = referral_earned + p_referral_reward WHERE telegram_id = ref.referrer_id;
      bonus_paid := FOUND;
    END IF;
  END IF;
  RETURN jsonb_build_object('reward', p_reward, 'referral_bonus_paid', bonus_paid);
END; $$;

CREATE OR REPLACE FUNCTION noxvolt_start_mining(p_telegram_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE u users%ROWTYPE;
BEGIN
  SELECT * INTO u FROM users WHERE telegram_id = p_telegram_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'User account not found'; END IF;
  IF u.mining_started_at IS NOT NULL THEN
    IF now() < u.mining_started_at + interval '1 hour' THEN RAISE EXCEPTION 'Mining already in progress';
    ELSE RAISE EXCEPTION 'Collect the completed mining reward first'; END IF;
  END IF;
  UPDATE users SET mining_started_at = now(), mining_last_collect = NULL WHERE telegram_id = p_telegram_id;
  RETURN jsonb_build_object('ok', true);
END; $$;

CREATE OR REPLACE FUNCTION noxvolt_collect_mining(p_telegram_id bigint, p_reward numeric, p_duration_seconds integer)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE u users%ROWTYPE;
BEGIN
  SELECT * INTO u FROM users WHERE telegram_id = p_telegram_id FOR UPDATE;
  IF NOT FOUND OR u.mining_started_at IS NULL THEN RAISE EXCEPTION 'No active mining session'; END IF;
  IF now() < u.mining_started_at + make_interval(secs => p_duration_seconds) THEN
    RAISE EXCEPTION 'Mining is not complete yet';
  END IF;
  UPDATE users SET withdrawable_balance = withdrawable_balance + p_reward,
    total_earned = total_earned + p_reward, mining_last_collect = now(), mining_started_at = NULL
    WHERE telegram_id = p_telegram_id;
  RETURN jsonb_build_object('reward', p_reward);
END; $$;

CREATE OR REPLACE FUNCTION noxvolt_claim_task(p_telegram_id bigint, p_task_id bigint)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE task_reward numeric;
BEGIN
  SELECT reward INTO task_reward FROM tasks WHERE id = p_task_id AND active = true;
  IF NOT FOUND THEN RAISE EXCEPTION 'Task not found or inactive'; END IF;
  INSERT INTO task_completions (telegram_id, task_id) VALUES (p_telegram_id, p_task_id);
  UPDATE users SET withdrawable_balance = withdrawable_balance + task_reward,
    total_earned = total_earned + task_reward WHERE telegram_id = p_telegram_id;
  IF NOT FOUND THEN RAISE EXCEPTION 'User account not found'; END IF;
  RETURN jsonb_build_object('reward', task_reward);
EXCEPTION WHEN unique_violation THEN
  RAISE EXCEPTION 'Task already completed';
END; $$;

CREATE OR REPLACE FUNCTION noxvolt_request_withdrawal(p_telegram_id bigint, p_address text, p_minimum numeric)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE u users%ROWTYPE;
BEGIN
  IF p_address IS NULL OR length(trim(p_address)) < 10 THEN RAISE EXCEPTION 'Invalid wallet address'; END IF;
  SELECT * INTO u FROM users WHERE telegram_id = p_telegram_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'User account not found'; END IF;
  IF u.withdrawable_balance < p_minimum THEN RAISE EXCEPTION 'Minimum withdrawal is % NOXV', p_minimum; END IF;
  INSERT INTO withdrawals (telegram_id, username, amount, address)
    VALUES (p_telegram_id, u.username, u.withdrawable_balance, trim(p_address));
  UPDATE users SET withdrawable_balance = 0, wallet = trim(p_address) WHERE telegram_id = p_telegram_id;
  RETURN jsonb_build_object('ok', true);
END; $$;

CREATE OR REPLACE FUNCTION noxvolt_process_withdrawal(p_withdrawal_id bigint, p_status text)
RETURNS jsonb LANGUAGE plpgsql SECURITY DEFINER SET search_path = public AS $$
DECLARE wd withdrawals%ROWTYPE;
BEGIN
  IF p_status NOT IN ('paid','rejected') THEN RAISE EXCEPTION 'Invalid withdrawal status'; END IF;
  SELECT * INTO wd FROM withdrawals WHERE id = p_withdrawal_id FOR UPDATE;
  IF NOT FOUND THEN RAISE EXCEPTION 'Withdrawal not found'; END IF;
  IF wd.status <> 'pending' THEN RAISE EXCEPTION 'Withdrawal already processed'; END IF;
  UPDATE withdrawals SET status = p_status, processed_at = now() WHERE id = p_withdrawal_id;
  IF p_status = 'rejected' THEN
    UPDATE users SET withdrawable_balance = withdrawable_balance + wd.amount WHERE telegram_id = wd.telegram_id;
  END IF;
  RETURN jsonb_build_object('ok', true);
END; $$;

